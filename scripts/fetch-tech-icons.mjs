/*
 * Vendors simple-icons paths into src/lib/tech-icons.ts so the marquee can
 * render brand logos with zero runtime/network dependencies.
 * Re-run after adding slugs: node scripts/fetch-tech-icons.mjs
 */
import { writeFileSync } from "node:fs";

const SLUGS = [
  "typescript",
  "javascript",
  "python",
  "react",
  "nextdotjs",
  "nodedotjs",
  "express",
  "fastapi",
  "django",
  "postgresql",
  "mongodb",
  "mysql",
  "tailwindcss",
  "mui",
  "redux",
  "vite",
  "threedotjs",
  "graphql",
  "prisma",
  "docker",
  "nginx",
  "figma",
  "redis",
  "git",
  "vercel",
  "framer",
  "playwright",
  "githubactions",
  "amazonwebservices",
  "amazonaws", // legacy alias — whichever resolves wins
  "langchain",
  "langgraph",
  "openai",
  "anthropic",
  "claude",
  "googlegemini",
  "livekit",
  "twilio",
  "apachekafka",
  "rabbitmq",
  "celery",
  "pytorch",
  "huggingface",
  "opencv",
  "elasticsearch",
  "opensearch",
  "apacheairflow",
  "qdrant",
];

const entries = {};
for (const slug of SLUGS) {
  const res = await fetch(`https://cdn.simpleicons.org/${slug}`);
  if (!res.ok) {
    console.warn(`skip ${slug}: ${res.status}`);
    continue;
  }
  const svg = await res.text();
  const match = svg.match(/ d="([^"]+)"/);
  if (!match) {
    console.warn(`skip ${slug}: no path`);
    continue;
  }
  entries[slug] = match[1];
  console.log(`ok ${slug}`);
}

const file = `// Generated by scripts/fetch-tech-icons.mjs — do not edit by hand.
// Brand icon paths from simple-icons (CC0), 24x24 viewBox.
export const TECH_ICON_PATHS: Record<string, string> = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(new URL("../src/lib/tech-icons.ts", import.meta.url), file);
console.log(`wrote ${Object.keys(entries).length} icons`);
